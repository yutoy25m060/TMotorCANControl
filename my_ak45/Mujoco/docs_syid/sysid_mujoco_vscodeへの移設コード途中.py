    # `raw_df` の時間情報を利用します。
    measured_times = raw_df.index.values.astype(np.float64) # 時間を秒単位のfloatに変換
    # もしCSVが相対時間（0から始まる）でない場合、最初のタイムスタンプを引いて0基点にすることも検討
    # measured_times = (measured_times - measured_times[0])

    # --- 制御信号 (トルク指令値など) の抽出 ---
